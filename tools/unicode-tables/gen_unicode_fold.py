#!/usr/bin/env python3
"""Generate src/unicode_fold_tables.h for the search's Unicode folding.

The search matches text after canonical decomposition (NFD) and, unless
case sensitive matching is on, case folding (find spec: "case folding
and normalisation of equivalent representations"). The tables come from
Python's unicodedata, so they follow the Unicode version of the Python
that generates them.

Regenerate with:
    python3 tools/unicode-tables/gen_unicode_fold.py
"""
import os
import sys
import unicodedata

MAX_SEQ = 4  # longest canonical decomposition after full recursion


def canonical_decomposition(cp):
    text = unicodedata.decomposition(chr(cp))
    if not text or text.startswith("<"):
        return None
    return [int(part, 16) for part in text.split()]


def nfd(cp):
    """The full canonical decomposition of one code point."""
    parts = canonical_decomposition(cp)
    if not parts:
        return [cp]
    out = []
    for part in parts:
        out.extend(nfd(part))
    return out


def nfd_stable(cp):
    return nfd(cp) == [cp]


def main():
    nfd_entries = []
    longest = 1
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        seq = nfd(cp)
        if len(seq) > 1:
            nfd_entries.append((cp, seq))
            longest = max(longest, len(seq))
    if longest > MAX_SEQ:
        print("decomposition longer than %d" % MAX_SEQ, file=sys.stderr)
        return 1

    # Folding happens after decomposition, so only code points that
    # survive NFD need an entry. ASCII folds are a fast path in the
    # runtime and stay out of the table.
    fold_entries = []
    longest_fold = 1
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF or cp < 0x80:
            continue
        if not nfd_stable(cp):
            continue
        folded = [ord(ch) for ch in chr(cp).casefold()]
        if folded != [cp]:
            fold_entries.append((cp, folded))
            longest_fold = max(longest_fold, len(folded))
    if longest_fold > 4:
        print("fold longer than 4", file=sys.stderr)
        return 1

    lines = []
    lines.append("// Generated by tools/unicode-tables/gen_unicode_fold.py with Python")
    lines.append("// %s and its unicodedata (Unicode %s). Do not edit by hand;"
                 % (sys.version.split()[0], unicodedata.unidata_version))
    lines.append("// regenerate instead.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace unicode {")
    lines.append("")
    lines.append("// A canonical decomposition (NFD), resolved to full depth.")
    lines.append("struct NfdEntry {")
    lines.append("    std::uint32_t code;")
    lines.append("    std::uint32_t count;")
    lines.append("    std::uint32_t seq[%d];" % MAX_SEQ)
    lines.append("};")
    lines.append("")
    lines.append("inline const NfdEntry kNfdEntries[] = {")
    for cp, seq in nfd_entries:
        padded = seq + [0] * (MAX_SEQ - len(seq))
        lines.append("    {0x%X, %d, {%s}}," % (
            cp, len(seq), ", ".join("0x%X" % v for v in padded)))
    lines.append("};")
    lines.append("inline const std::size_t kNfdEntryCount =")
    lines.append("    sizeof(kNfdEntries) / sizeof(kNfdEntries[0]);")
    lines.append("")
    lines.append("// A case fold of a code point that survives canonical")
    lines.append("// decomposition; one entry per code point whose folded form is")
    lines.append("// different (one code point, or an expansion like the sharp s).")
    lines.append("struct FoldEntry {")
    lines.append("    std::uint32_t code;")
    lines.append("    std::uint32_t count;")
    lines.append("    std::uint32_t seq[4];")
    lines.append("};")
    lines.append("")
    lines.append("inline const FoldEntry kFoldEntries[] = {")
    for cp, seq in fold_entries:
        padded = seq + [0] * (4 - len(seq))
        lines.append("    {0x%X, %d, {%s}}," % (
            cp, len(seq), ", ".join("0x%X" % v for v in padded)))
    lines.append("};")
    lines.append("inline const std::size_t kFoldEntryCount =")
    lines.append("    sizeof(kFoldEntries) / sizeof(kFoldEntries[0]);")
    lines.append("")
    lines.append("}  // namespace unicode")
    lines.append("")

    root = os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))))
    out = os.path.join(root, "src", "unicode_fold_tables.h")
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print("wrote %s: %d decomposition entries, %d fold entries"
          % (out, len(nfd_entries), len(fold_entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
